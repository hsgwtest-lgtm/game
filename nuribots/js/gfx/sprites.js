// 文字列のドット絵を {w,h,d} に変換（1色アイコン用）
const cache = new Map();
export function bitmap(rows) {
  let b = cache.get(rows);
  if (b) return b;
  const h = rows.length, w = Math.max(...rows.map(r => r.length));
  const d = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < rows[y].length; x++) if (rows[y][x] !== '.') d[y * w + x] = 1;
  b = { w, h, d };
  cache.set(rows, b);
  return b;
}
