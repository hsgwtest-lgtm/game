// ドット絵のアイコン（文字で描いて、起動時に配列にする）

import { rgb } from './fb.js';

function I(rows) {
  const h = rows.length, w = rows[0].length;
  const d = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) d[y * w + x] = rows[y][x] === '#' ? 1 : 0;
  return { w, h, d };
}
// 色つきスプライト: rows の各文字を map の色に。'.' は透明
export function S(rows, map) {
  const h = rows.length, w = rows[0].length;
  const keys = Object.keys(map);
  const d = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const k = keys.indexOf(rows[y][x]);
    d[y * w + x] = k >= 0 ? k + 1 : 0;
  }
  return { w, h, d, cols: [0, ...keys.map(k => rgb(map[k]))] };
}

